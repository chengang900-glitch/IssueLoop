CREATE TABLE work_item_relations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_work_item_id VARCHAR(16) NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    target_work_item_id VARCHAR(16) NOT NULL REFERENCES work_items(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_work_item_relation UNIQUE (source_work_item_id, target_work_item_id)
);

CREATE INDEX idx_work_item_relations_source ON work_item_relations(source_work_item_id);
CREATE INDEX idx_work_item_relations_target ON work_item_relations(target_work_item_id);
